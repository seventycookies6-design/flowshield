"""
Generate the app's and the site's colour tokens from design/tokens.json.

    python tools/build_tokens.py          # rewrite the generated files
    python tools/build_tokens.py --check  # exit 1 if any generated file is stale

Writes:
  DesktopApp/Styles/Tokens.xaml         dark theme (the app's current theme)
  DesktopApp/Styles/Tokens.Light.xaml   light theme (not loaded until the app gains one)
  Website/styles.css                    only the text between the tokens:light and
                                        tokens:dark markers; the rest is hand-written
  AppleApps/Basalt/Tokens.xcassets      one colour set per app token (light, with a dark
                                        appearance), plus AccentColor = primary, for the
                                        Mac app (#426); the Windows depth tokens in
                                        apple_skip are left out

The XAML also carries app_brushes: the elevation surfaces, the gradients and
the drop shadows, which are more than one colour but must still swap with the
theme (DESIGN_SYSTEM.md Part A, Depth).

Colours used to be typed twice, once in Theme.xaml and once in styles.css, and
the two drifted. This makes the JSON the only place a colour is defined.
See DESIGN_SYSTEM.md, section 14.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.json"
XAML_OUT = {
    "dark": ROOT / "DesktopApp" / "Styles" / "Tokens.xaml",
    "light": ROOT / "DesktopApp" / "Styles" / "Tokens.Light.xaml",
}
CSS = ROOT / "Website" / "styles.css"
XCASSETS = ROOT / "AppleApps" / "Basalt" / "Tokens.xcassets"

HEADER = "Generated by tools/build_tokens.py from design/tokens.json. Do not edit by hand."


def _hex(value: str) -> tuple[int, int, int]:
    value = value.lstrip("#")
    if not re.fullmatch(r"[0-9A-Fa-f]{6}", value):
        raise ValueError(f"not a #RRGGBB colour: #{value}")
    return int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16)


def resolve(theme: dict, name: str, seen: tuple[str, ...] = ()) -> tuple[int, int, int, float]:
    """A token as (r, g, b, alpha), following {"ref", "alpha"} references."""
    if name in seen:
        raise ValueError(f"circular token reference: {' -> '.join(seen + (name,))}")
    value = theme[name]
    if isinstance(value, str):
        return (*_hex(value), 1.0)
    r, g, b, _ = resolve(theme, value["ref"], seen + (name,))
    return r, g, b, float(value["alpha"])


def _alpha_byte(alpha: float) -> int:
    return max(0, min(255, round(alpha * 255)))


def _fmt_alpha(alpha: float) -> str:
    return f"{alpha:.2f}".rstrip("0").rstrip(".") if alpha not in (0, 1) else str(int(alpha))


def xaml(data: dict, theme_name: str) -> str:
    theme = data["themes"][theme_name]
    lines = [
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
        f"    <!-- {HEADER} Theme: {theme_name}. -->",
        "",
    ]
    for token, key in data["app_names"].items():
        r, g, b, a = resolve(theme, token)
        argb = f"#{_alpha_byte(a):02X}{r:02X}{g:02X}{b:02X}"
        lines.append(f'    <Color x:Key="{key}Color">{argb}</Color>')
    lines.append("")
    for token, key in data["app_names"].items():
        lines.append(f'    <SolidColorBrush x:Key="{key}" Color="{{StaticResource {key}Color}}"/>')
    brushes = data.get("app_brushes", {})
    if brushes:
        lines.append("")
        for key, spec in brushes.items():
            lines += _brush(data, theme_name, key, spec)
    lines += ["</ResourceDictionary>", ""]
    return "\n".join(lines)


def _argb(rgba: tuple[int, int, int, float]) -> str:
    r, g, b, a = rgba
    return f"#{_alpha_byte(a):02X}{r:02X}{g:02X}{b:02X}"


def _stop_colour(theme: dict, stop) -> tuple[int, int, int, float]:
    """A gradient stop: a token name, or {"ref": token, "alpha": a} to override its alpha."""
    if isinstance(stop, str):
        return resolve(theme, stop)
    r, g, b, _ = resolve(theme, stop["ref"])
    return r, g, b, float(stop["alpha"])


def composite(top: tuple[int, int, int, float], base: tuple[int, int, int, float]) -> tuple[int, int, int, float]:
    """top painted over an opaque base, as the one opaque colour the eye sees."""
    r1, g1, b1, a = top
    r2, g2, b2, _ = base
    mix = lambda f, t: round(f * a + t * (1 - a))
    return mix(r1, r2), mix(g1, g2), mix(b1, b2), 1.0


def _brush(data: dict, theme_name: str, key: str, spec: dict) -> list[str]:
    """One multi-colour resource from app_brushes, for this theme.

    surface: an elevation (DESIGN_SYSTEM.md Part A, Depth). WPF has no inset
      box-shadow, so the top highlight is painted as the background's first
      rows: an absolute-mapped gradient whose band covers y 0 to 2, of which
      the row below a Border's 1 px hairline is what shows. The highlight is
      composited onto the base here, so the band is opaque like the base.
    linear / radial: a gradient between two tokens.
    shadow: a DropShadowEffect falling straight down (Direction 270), black
      at the theme's opacity. Shadows are never coloured.
    """
    theme = data["themes"][theme_name]
    kind = spec["kind"]
    if kind == "surface":
        base = resolve(theme, spec["base"])
        top = composite(resolve(theme, spec["top"]), base)
        return [
            f'    <LinearGradientBrush x:Key="{key}" MappingMode="Absolute" StartPoint="0,0" EndPoint="0,2">',
            f'        <GradientStop Color="{_argb(top)}" Offset="0"/>',
            f'        <GradientStop Color="{_argb(top)}" Offset="1"/>',
            f'        <GradientStop Color="{_argb(base)}" Offset="1"/>',
            "    </LinearGradientBrush>",
        ]
    if kind in ("linear", "radial"):
        first, last = _argb(_stop_colour(theme, spec["from"])), _argb(_stop_colour(theme, spec["to"]))
        head = (f'    <LinearGradientBrush x:Key="{key}" StartPoint="{spec["start"]}" EndPoint="{spec["end"]}">'
                if kind == "linear" else f'    <RadialGradientBrush x:Key="{key}">')
        tail = "    </LinearGradientBrush>" if kind == "linear" else "    </RadialGradientBrush>"
        return [head,
                f'        <GradientStop Color="{first}" Offset="0"/>',
                f'        <GradientStop Color="{last}" Offset="1"/>',
                tail]
    if kind == "shadow":
        opacity = _fmt_alpha(float(spec["opacity"][theme_name]))
        return [f'    <DropShadowEffect x:Key="{key}" BlurRadius="{spec["blur"]}" ShadowDepth="{spec["depth"]}" '
                f'Direction="270" Opacity="{opacity}" Color="{{StaticResource ShadowColor}}"/>']
    raise ValueError(f"app_brushes.{key}: unknown kind {kind!r}")


def css_block(data: dict, theme_name: str, indent: str = "  ") -> str:
    theme = data["themes"][theme_name]
    skip = set(data.get("css_skip", []))
    out = [f"{indent}/* {HEADER} */"]
    for token in theme:
        if token in skip:
            continue
        r, g, b, a = resolve(theme, token)
        value = f"#{r:02x}{g:02x}{b:02x}" if a == 1.0 else f"rgba({r}, {g}, {b}, {_fmt_alpha(a)})"
        out.append(f"{indent}--color-{token}: {value};")
    out.append("")
    for name, value in data["css_only"][theme_name].items():
        out.append(f"{indent}--{name}: {value};")
    return "\n".join(out)


def css(data: dict, current: str) -> str:
    """Replace each marked block in styles.css, leaving everything else untouched."""
    updated = current
    for theme_name in ("light", "dark"):
        pattern = re.compile(
            rf"(/\* tokens:{theme_name}:start \*/\r?\n)(.*?)(\r?\n[ \t]*/\* tokens:{theme_name}:end \*/)",
            re.S,
        )
        if not pattern.search(updated):
            raise ValueError(f"styles.css is missing the tokens:{theme_name} markers")
        block = css_block(data, theme_name)
        updated = pattern.sub(lambda m: m.group(1) + block + m.group(3), updated, count=1)
    return updated


def _colorset_entry(rgba: tuple[int, int, int, float], dark: bool) -> dict:
    r, g, b, a = rgba
    entry = {
        "color": {
            "color-space": "srgb",
            "components": {
                "alpha": f"{a:.3f}",
                "blue": f"0x{b:02X}",
                "green": f"0x{g:02X}",
                "red": f"0x{r:02X}",
            },
        },
        "idiom": "universal",
    }
    if dark:
        entry = {"appearances": [{"appearance": "luminosity", "value": "dark"}], **entry}
    return entry


def colorset(data: dict, token: str) -> str:
    """An asset-catalog colour set: the light value, then the dark one as an appearance."""
    body = {
        "colors": [
            _colorset_entry(resolve(data["themes"]["light"], token), dark=False),
            _colorset_entry(resolve(data["themes"]["dark"], token), dark=True),
        ],
        "info": {"author": "xcode", "version": 1},
    }
    return json.dumps(body, indent=2) + "\n"


def xcassets(data: dict) -> dict[Path, str]:
    """The Mac app's colours, named like the WPF resource keys so both apps read alike."""
    files = {XCASSETS / "Contents.json": json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n"}
    skip = set(data.get("apple_skip", []))
    for token, key in data["app_names"].items():
        if token in skip:
            continue
        files[XCASSETS / f"{key}.colorset" / "Contents.json"] = colorset(data, token)
    files[XCASSETS / "AccentColor.colorset" / "Contents.json"] = colorset(data, "primary")
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--check", action="store_true",
                        help="report stale generated files instead of writing them")
    args = parser.parse_args()

    data = json.loads(TOKENS.read_text(encoding="utf-8"))

    wanted: dict[Path, str] = {path: xaml(data, theme) for theme, path in XAML_OUT.items()}
    wanted[CSS] = css(data, CSS.read_bytes().decode("utf-8").replace("\r\n", "\n"))
    wanted.update(xcassets(data))

    stale = []
    for path, content in wanted.items():
        # Compare ignoring line endings: git checks files out with CRLF on
        # Windows and LF elsewhere (.gitattributes text=auto).
        existing = path.read_bytes().decode("utf-8").replace("\r\n", "\n") if path.exists() else None
        if existing != content.replace("\r\n", "\n"):
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content.encode("utf-8"))

    rel = [str(p.relative_to(ROOT)) for p in stale]
    if args.check:
        if stale:
            print("stale generated token files (run python tools/build_tokens.py): " + ", ".join(rel))
            return 1
        print("token files are up to date")
        return 0
    print("wrote: " + (", ".join(rel) if rel else "nothing (already up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
